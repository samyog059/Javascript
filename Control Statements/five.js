let marks = 95;

switch (true) {
    case marks >= 90:
        console.log("A+");
        break;

    case marks >= 80:
        console.log("A");
        break;

    case marks >= 70:
        console.log("B+");
        break;

    case marks >= 60:
        console.log("B");
        break;

    case marks >= 50:
        console.log("C");
        break;

    default:
        console.log("Fail");
}
